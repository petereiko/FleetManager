class TableExporter {
    // Configuration - Set these values from your ASP.NET backend
    static config = {
        companyName: 'Your Company Ltd',
        companyAddress: '123 Business Street, Lagos, Nigeria',
        companyPhone: '+234 123 456 7890',
        companyEmail: 'info@yourcompany.com',
        userName: 'John Doe', // From User.Identity.Name
        userRole: 'Administrator', // From User role
        exportedBy: 'System Administrator'
    };

    // Method to update config from backend
    static setConfig(config) {
        this.config = { ...this.config, ...config };
    }

    static showLoading() {
        document.getElementById('exportLoading').style.display = 'block';
    }

    static hideLoading() {
        document.getElementById('exportLoading').style.display = 'none';
    }

    static showSuccess() {
        const success = document.getElementById('exportSuccess');
        success.style.display = 'block';
        setTimeout(() => {
            success.style.display = 'none';
        }, 3000);
    }

    static getReportHeader() {
        const now = new Date();
        return {
            title: 'Data Export Report',
            generatedOn: now.toLocaleString('en-NG', {
                year: 'numeric',
                month: 'long',
                day: 'numeric',
                hour: '2-digit',
                minute: '2-digit'
            }),
            generatedBy: this.config.userName,
            userRole: this.config.userRole,
            company: this.config.companyName,
            address: this.config.companyAddress,
            contact: `${this.config.companyPhone} | ${this.config.companyEmail}`
        };
    }

    static getTableData(tableSelector) {
        const table = document.querySelector(tableSelector);
        if (!table) {
            throw new Error(`Table with selector "${tableSelector}" not found`);
        }

        const headers = [];
        const rows = [];

        // Extract headers
        const headerCells = table.querySelectorAll('thead th');
        headerCells.forEach(cell => {
            // Clean header text by removing icons and extra whitespace
            let headerText = cell.textContent.trim();
            // Remove FontAwesome icons and sort indicators
            headerText = headerText.replace(/[\uf000-\uf8ff]/g, '').trim();
            headers.push(headerText);
        });

        // Extract rows
        const bodyRows = table.querySelectorAll('tbody tr');
        bodyRows.forEach(row => {
            const rowData = [];
            const cells = row.querySelectorAll('td');

            cells.forEach(cell => {
                let cellText = '';

                // Check if cell contains form elements
                const select = cell.querySelector('select');
                const button = cell.querySelector('button');

                if (select) {
                    // Get selected option text
                    cellText = select.options[select.selectedIndex].text;
                } else if (button) {
                    // Skip action buttons
                    cellText = '';
                } else {
                    // Clean cell text
                    cellText = cell.textContent.trim();
                    // Replace multiple whitespaces with single space
                    cellText = cellText.replace(/\s+/g, ' ');
                }

                rowData.push(cellText);
            });

            // Only add row if it has meaningful data
            if (rowData.some(data => data.length > 0)) {
                rows.push(rowData);
            }
        });

        return { headers, rows };
    }

    static async exportToExcel(tableSelector, filename = 'table_data') {
        try {
            this.showLoading();

            const { headers, rows } = this.getTableData(tableSelector);
            const reportHeader = this.getReportHeader();

            // Create workbook and worksheet
            const wb = XLSX.utils.book_new();

            // Create header information
            const headerInfo = [
                [reportHeader.company],
                [reportHeader.address],
                [reportHeader.contact],
                [''],
                [reportHeader.title],
                [`Generated on: ${reportHeader.generatedOn}`],
                [`Generated by: ${reportHeader.generatedBy} (${reportHeader.userRole})`],
                [''],
                headers,
                ...rows
            ];

            const ws = XLSX.utils.aoa_to_sheet(headerInfo);

            // Style the header
            const range = XLSX.utils.decode_range(ws['!ref']);

            // Company name styling
            if (ws['A1']) {
                ws['A1'].s = {
                    font: { bold: true, size: 16, color: { rgb: "1F4E79" } },
                    alignment: { horizontal: "center" }
                };
            }

            // Merge company name across columns
            ws['!merges'] = [
                { s: { r: 0, c: 0 }, e: { r: 0, c: headers.length - 1 } },
                { s: { r: 1, c: 0 }, e: { r: 1, c: headers.length - 1 } },
                { s: { r: 2, c: 0 }, e: { r: 2, c: headers.length - 1 } },
                { s: { r: 4, c: 0 }, e: { r: 4, c: headers.length - 1 } }
            ];

            // Auto-size columns
            const colWidths = headers.map((header, i) => {
                const maxLength = Math.max(
                    header.length,
                    ...rows.map(row => String(row[i] || '').length)
                );
                return { wch: Math.min(maxLength + 2, 50) };
            });
            ws['!cols'] = colWidths;

            // Add worksheet to workbook
            XLSX.utils.book_append_sheet(wb, ws, 'Report');

            // Save file
            const timestamp = new Date().toISOString().split('T')[0];
            XLSX.writeFile(wb, `${filename}_${timestamp}.xlsx`);

            this.hideLoading();
            this.showSuccess();
        } catch (error) {
            this.hideLoading();
            alert('Error exporting to Excel: ' + error.message);
        }
    }

    static async exportToPDF(tableSelector, filename = 'table_data') {
        try {
            this.showLoading();

            const { headers, rows } = this.getTableData(tableSelector);
            const reportHeader = this.getReportHeader();

            const { jsPDF } = window.jspdf;
            const doc = new jsPDF();

            // Company Header
            doc.setFontSize(18);
            doc.setFont(undefined, 'bold');
            doc.setTextColor(31, 78, 121); // Company color
            doc.text(reportHeader.company, 105, 20, { align: 'center' });

            // Company details
            doc.setFontSize(10);
            doc.setFont(undefined, 'normal');
            doc.setTextColor(100, 100, 100);
            doc.text(reportHeader.address, 105, 28, { align: 'center' });
            doc.text(reportHeader.contact, 105, 34, { align: 'center' });

            // Report Title
            doc.setFontSize(14);
            doc.setFont(undefined, 'bold');
            doc.setTextColor(0, 0, 0);
            doc.text(reportHeader.title, 105, 50, { align: 'center' });

            // Report Info
            doc.setFontSize(9);
            doc.setFont(undefined, 'normal');
            doc.setTextColor(80, 80, 80);
            doc.text(`Generated on: ${reportHeader.generatedOn}`, 20, 60);
            doc.text(`Generated by: ${reportHeader.generatedBy} (${reportHeader.userRole})`, 20, 66);

            // Add separator line
            doc.setDrawColor(200, 200, 200);
            doc.line(20, 72, 190, 72);

            // Add table
            doc.autoTable({
                head: [headers],
                body: rows,
                startY: 80,
                theme: 'grid',
                headStyles: {
                    fillColor: [31, 78, 121],
                    textColor: 255,
                    fontStyle: 'bold',
                    fontSize: 10
                },
                alternateRowStyles: {
                    fillColor: [248, 249, 250]
                },
                styles: {
                    fontSize: 9,
                    cellPadding: 4,
                    textColor: 50
                },
                margin: { left: 20, right: 20 }
            });

            // Footer
            const pageCount = doc.internal.getNumberOfPages();
            for (let i = 1; i <= pageCount; i++) {
                doc.setPage(i);
                doc.setFontSize(8);
                doc.setTextColor(150, 150, 150);
                doc.text(`Page ${i} of ${pageCount}`, 105, 285, { align: 'center' });
                doc.text(`© ${new Date().getFullYear()} ${reportHeader.company}`, 105, 290, { align: 'center' });
            }

            // Save file
            const timestamp = new Date().toISOString().split('T')[0];
            doc.save(`${filename}_${timestamp}.pdf`);

            this.hideLoading();
            this.showSuccess();
        } catch (error) {
            this.hideLoading();
            alert('Error exporting to PDF: ' + error.message);
        }
    }

    static async exportToCSV(tableSelector, filename = 'table_data') {
        try {
            this.showLoading();

            const { headers, rows } = this.getTableData(tableSelector);
            const reportHeader = this.getReportHeader();

            // Create CSV content with header information
            const headerLines = [
                reportHeader.company,
                reportHeader.address,
                reportHeader.contact,
                '',
                reportHeader.title,
                `Generated on: ${reportHeader.generatedOn}`,
                `Generated by: ${reportHeader.generatedBy} (${reportHeader.userRole})`,
                ''
            ];

            // Combine header info and data
            const csvContent = [...headerLines, headers.join(',')]
                .concat(rows.map(row => row.map(cell => {
                    // Escape quotes and wrap in quotes if necessary
                    const cellStr = String(cell || '');
                    if (cellStr.includes(',') || cellStr.includes('"') || cellStr.includes('\n')) {
                        return `"${cellStr.replace(/"/g, '""')}"`;
                    }
                    return cellStr;
                }).join(',')))
                .join('\n');

            // Create and download file
            const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
            const link = document.createElement('a');
            const url = URL.createObjectURL(blob);

            link.setAttribute('href', url);
            const timestamp = new Date().toISOString().split('T')[0];
            link.setAttribute('download', `${filename}_${timestamp}.csv`);
            link.style.visibility = 'hidden';

            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);

            this.hideLoading();
            this.showSuccess();
        } catch (error) {
            this.hideLoading();
            alert('Error exporting to CSV: ' + error.message);
        }
    }
}

// Global functions for easy access
window.exportToExcel = (tableSelector, filename) => TableExporter.exportToExcel(tableSelector, filename);
window.exportToPDF = (tableSelector, filename) => TableExporter.exportToPDF(tableSelector, filename);
window.exportToCSV = (tableSelector, filename) => TableExporter.exportToCSV(tableSelector, filename);
















